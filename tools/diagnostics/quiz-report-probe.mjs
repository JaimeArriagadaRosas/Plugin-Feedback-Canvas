import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import dotenv from 'dotenv';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
dotenv.config({path:path.join(root,'.env'),quiet:true});
process.env.STARTUP_MODE='3';
const local=JSON.parse(fs.readFileSync(path.join(root,'tmp/canvas_local_users.json'),'utf8')).usuarios;
const teacher=local.find(u=>u.email==='profesor@canvas.local');
const {default:CanvasClient}=await import('../../apps/server/src/services/infrastructure/CanvasClient.js');
const canvas=new CanvasClient('http://127.0.0.1:8080');
const endpoint='/courses/1/quizzes/6/reports';
const reports=await canvas.apiFetch(endpoint,teacher.token,{maxRetries:1});
console.log('EXISTING_REPORTS',JSON.stringify(reports).slice(0,1400));
const report=await canvas.apiFetch(endpoint+'/1',teacher.token,{maxRetries:1});
console.log('REPORT_DETAIL',JSON.stringify(report).slice(0,1800));
const progress=await canvas.apiFetch('/progress/1',teacher.token,{maxRetries:1});
console.log('REPORT_PROGRESS',JSON.stringify(progress).slice(0,1100));
const {default:Gateway}=await import('../../apps/server/src/adapters/CanvasLmsAdapter.js');
const gateway=new Gateway(canvas,{getValidToken:async()=>teacher.token});
const {buffer}=await gateway.downloadSubmissionAttachment({id:report.file.id,filename:report.file.filename},teacher.email);
const content=buffer.toString('utf8');
console.log('CSV_REPORT',content.slice(0,1900));
