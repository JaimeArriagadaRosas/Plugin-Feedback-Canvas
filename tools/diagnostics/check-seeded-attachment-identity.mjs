import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import dotenv from 'dotenv';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
dotenv.config({path:path.join(root,'.env'),quiet:true});
process.env.STARTUP_MODE='3';
const users=JSON.parse(fs.readFileSync(path.join(root,'tmp/canvas_local_users.json'),'utf8')).usuarios;
const teacher=users.find(u=>u.email==='profesor@canvas.local');
if(!teacher?.token) throw new Error('Token local de prueba no disponible');
const {default:CanvasClient}=await import('../../apps/server/src/services/infrastructure/CanvasClient.js');
const {default:CanvasLmsAdapter}=await import('../../apps/server/src/adapters/CanvasLmsAdapter.js');
const gateway=new CanvasLmsAdapter(new CanvasClient(process.env.CANVAS_BASE_URL||'https://localhost:8443'),{getValidToken:async()=>teacher.token});
const course=2,assignment=5,studentId=9;
const [students,submission]=await Promise.all([gateway.getStudents(course,teacher.email),gateway.getSubmission(course,assignment,studentId,teacher.email)]);
const student=students.find(u=>String(u.id)===String(studentId));
if(!student?.name) throw new Error('El estudiante no se encontró en el curso');
const attachments=submission.attachments||[];
const slug=s=>String(s).normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,'_').replace(/^_|_$/g,'');
const mismatches=attachments.filter(a=>!slug(a.filename).includes(slug(student.name)));
console.log(JSON.stringify({course,assignment,studentId,canvasStudent:student.name,attachments:attachments.map(a=>a.filename),mismatches:mismatches.map(a=>a.filename),status:mismatches.length?'FIXTURE_MISMATCH_DETECTED':'NO_MISMATCH_DETECTED',aiCalls:0,dbWrites:0}));
if(mismatches.length===0)throw new Error('La inconsistencia conocida de la semilla ya no se reproduce; revisar fixtures');
